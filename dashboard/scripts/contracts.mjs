import { mkdir, readFile, writeFile } from "node:fs/promises";
import { compile } from "json-schema-to-typescript";
import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneModule from "ajv/dist/standalone/index.js";
import { _ } from "ajv/dist/compile/codegen/index.js";

const schema = JSON.parse(await readFile(new URL("../schemas/responses.json", import.meta.url), "utf8"));
const names = [
  "DashboardPayload", "DatabaseDetails", "DatabasePage", "EstateSummary",
  "IncidentPage", "MetricHistory", "ScenarioCatalogue",
];
const ajv = new Ajv2020({
  strict: false, allErrors: true,
  code: { source: true, esm: true, formats: _`fullFormats` },
});
addFormats(ajv);
ajv.addSchema(schema, "public");
const validators = standaloneModule.default(ajv,
  Object.fromEntries(names.map((name) => [name, `public#/$defs/${name}`])));
const declarations = [
  'import type { ValidateFunction } from "ajv";',
  'import type * as Contracts from "../contracts";',
  ...names.map((name) => `export const ${name}: ValidateFunction<Contracts.${name}>;`),
].join("\n") + "\n";
const outputs = {
  "src/contracts.ts": await compile(schema, "PublicContracts"),
  "src/generated/validators.js":
    '// Generated by scripts/contracts.mjs. Do not edit.\n' +
    'import { fullFormats } from "ajv-formats/dist/formats.js";\n' + validators + "\n",
  "src/generated/validators.d.ts": declarations,
};
for (const [name, expected] of Object.entries(outputs)) {
  const path = new URL(`../${name}`, import.meta.url);
  if (process.argv.includes("--check")) {
    const actual = await readFile(path, "utf8");
    if (expected.replaceAll("\r\n", "\n") !== actual.replaceAll("\r\n", "\n")) {
      console.error(`${name} is stale; run npm run generate:contracts`);
      process.exitCode = 1;
    }
  } else {
    await mkdir(new URL(".", path), { recursive: true });
    await writeFile(path, expected);
  }
}
